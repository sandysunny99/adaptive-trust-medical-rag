    def _abstain(
        self,
        *,
        session_id: str,
        query_hash: str,
        risk_tier: str,
        reason: str,
        audit: dict,
        verification: VerificationReport | None = None,
        trust_scores: list[float] | None = None,
        chunk_ids: list[str] | None = None,
        security_context: SecurityContext | None = None,
    ) -> RAGResponse:
        """Return a structured abstention response."""
        threshold = EvidenceEligibilityGate.TIER_THRESHOLDS.get(risk_tier, 0.45)
        answer = ABSTENTION_TEMPLATE.format(
            risk_tier=risk_tier,
            threshold=threshold,
            reason=reason,
        )
        return RAGResponse(
            session_id=session_id,
            query_hash=query_hash,
            risk_tier=risk_tier,
            status=PipelineStatus.abstained,
            answer=answer,
            confidence=0.0,
            trust_scores=trust_scores or [],
            retrieved_chunk_ids=chunk_ids or [],
            gate_decision="abstain",
            verification_report=verification,
            audit_log=audit,
            security_events=security_context.cumulative_decisions if security_context else []
        )

    @staticmethod
    def _extract_drugs_simple(query: str) -> list[str]:
        """
        Fallback drug extractor: match known pharmacological suffixes.
        Used when no DrugNormalizerProtocol is injected.
        """
        pattern = re.compile(
            r"\b[A-Za-z]{3,}(?:mab|nib|olol|pril|sartan|statin|mycin|cillin|"
            r"cycline|azole|warfarin|metformin|aspirin|insulin|heparin)\b",
            re.IGNORECASE,
        )
        return list({m.lower() for m in pattern.findall(query)})

