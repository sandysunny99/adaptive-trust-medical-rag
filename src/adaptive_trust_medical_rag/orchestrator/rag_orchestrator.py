_PROMPT_TEMPLATE = """\
You are a medical evidence synthesis assistant. Your task is to answer the \
clinical pharmacology query below using ONLY the retrieved evidence provided. \
Do NOT generate information not present in the evidence. \
Cite each factual claim with [Source N] where N is the evidence index.

QUERY: {query}

RISK TIER: {risk_tier} â€” {risk_description}

RETRIEVED EVIDENCE:
{evidence_block}

INSTRUCTIONS:
- Answer in clear, precise clinical language.
- Every factual claim MUST be cited with [Source N].
- If the evidence is insufficient to answer, state that clearly.
- Do NOT speculate beyond the retrieved evidence.
- Do NOT fabricate citations, PMIDs, or dosing data.
"""

_RISK_DESCRIPTIONS = {
    "R0": "Informational / General pharmacology",
    "R1": "Standard clinical guidance",
    "R2": "High caution â€” vulnerable populations / black-box warnings",
    "R3": "Critical safety / contraindications / narrow therapeutic index",
}


def build_grounded_prompt(
    query: str,
    risk_tier: str,
    candidates: list[ScoredCandidate],
) -> str:
    """Build a structured, grounded prompt from retrieved evidence candidates."""
    evidence_lines: list[str] = []
    for i, sc in enumerate(candidates, start=1):
        auth = sc.candidate.source_authority
        evidence_lines.append(
            f"[Source {i}] (authority={auth:.2f}, chunk={sc.candidate.chunk_id})\n"
            f"{sc.candidate.text.strip()}"
        )
    evidence_block = "\n\n".join(evidence_lines) if evidence_lines else "(No evidence retrieved)"
    return _PROMPT_TEMPLATE.format(
        query=query,
        risk_tier=risk_tier,
        risk_description=_RISK_DESCRIPTIONS.get(risk_tier, "Unknown"),
        evidence_block=evidence_block,
    )


