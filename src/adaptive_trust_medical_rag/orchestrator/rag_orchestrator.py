class EvidenceEligibilityGate:
    """
    Pre-generation gate: evaluates retrieved chunks before LLM context is built.

    Rejects chunks that:
    - Have poisoning_score > 0.4
    - Have trust_score below the risk-tier threshold
    - Have source_authority below minimum viable authority (0.3)

    If too few eligible chunks remain, triggers abstention.
    """

    MIN_AUTHORITY: float = 0.3
    MIN_ELIGIBLE_CHUNKS: int = 1

    #: Trust score thresholds per risk tier (mirrors medical-safety rules)
    TIER_THRESHOLDS: dict[str, float] = {
        "R0": 0.30,
        "R1": 0.45,
        "R2": 0.60,
        "R3": 0.75,
    }

    def evaluate(
        self,
        candidates: list[ScoredCandidate],
        risk_tier: str,
        trust_scores: dict[str, float],
        retrieval_security_states: dict[str, SecurityDecision] | None = None,
        grounding_states: dict = None,
        integrity_states: dict = None,
        candidate_injection_states: dict = None,
    ) -> EvidenceEligibilityResult:
        threshold = self.TIER_THRESHOLDS.get(risk_tier, 0.45)
        eligible: list[ScoredCandidate] = []
        rejected_ids: list[str] = []
        reasons: dict[str, str] = {}

        for sc in candidates:
            cand = sc.candidate
            trust = trust_scores.get(cand.chunk_id, 0.0)

            if retrieval_security_states and cand.chunk_id in retrieval_security_states:
                sec_state = retrieval_security_states[cand.chunk_id].decision
                if sec_state == SecurityState.BLOCK:
                    rejected_ids.append(cand.chunk_id)
                    reasons[cand.chunk_id] = retrieval_security_states[cand.chunk_id].reason_code
                    continue
                    
            if integrity_states and cand.chunk_id in integrity_states:
                if integrity_states[cand.chunk_id].status.name == 'MISMATCH':
                    rejected_ids.append(cand.chunk_id)
                    reasons[cand.chunk_id] = 'INTEGRITY_MISMATCH'
                    continue
                elif integrity_states[cand.chunk_id].status.name == 'MISSING':
                    rejected_ids.append(cand.chunk_id)
                    reasons[cand.chunk_id] = 'INTEGRITY_MISSING_REFERENCE'
                    continue

            if grounding_states and cand.chunk_id in grounding_states:
                g_status = grounding_states[cand.chunk_id].status.name
                if g_status in ('UNSUPPORTED', 'CONTRADICTED', 'NO_RELEVANT_RELATION', 'ENTITY_PAIR_MISMATCH', 'UNVERIFIABLE'):
                    rejected_ids.append(cand.chunk_id)
                    reasons[cand.chunk_id] = 'RELATIONSHIP_GROUNDING_UNSUPPORTED'
                    continue
                elif g_status == 'AMBIGUOUS':
                    # Project policy: fail-closed for ambiguous relationships
                    rejected_ids.append(cand.chunk_id)
                    reasons[cand.chunk_id] = 'RELATIONSHIP_GROUNDING_AMBIGUOUS'
                    continue

            if candidate_injection_states and cand.chunk_id in candidate_injection_states:
                sec_state = candidate_injection_states[cand.chunk_id].decision
                if sec_state in (SecurityState.BLOCK, SecurityState.FLAG):
                    rejected_ids.append(cand.chunk_id)
                    reasons[cand.chunk_id] = 'PROMPT_INJECTION_DETECTED'
                    continue

            if cand.poisoning_score > 0.4:
                rejected_ids.append(cand.chunk_id)
                reasons[cand.chunk_id] = 'HIGH_POISONING_SCORE'
                continue

            if trust < threshold:
                rejected_ids.append(cand.chunk_id)
                reasons[cand.chunk_id] = 'INSUFFICIENT_TRUST'
                continue

            if cand.source_authority < self.MIN_AUTHORITY:
                rejected_ids.append(cand.chunk_id)
                reasons[cand.chunk_id] = 'LOW_AUTHORITY'
                continue

            eligible.append(sc)

        if len(eligible) < self.MIN_ELIGIBLE_CHUNKS:
            return EvidenceEligibilityResult(
                passed=False,
                eligible_chunks=[],
                rejected_chunk_ids=rejected_ids,
                reason=f'Insufficient eligible evidence: {len(eligible)} chunk(s) passed all gates. {len(rejected_ids)} chunk(s) rejected.',
                rejection_reasons=reasons,
            )

        return EvidenceEligibilityResult(
            passed=True,
            eligible_chunks=eligible,
            rejected_chunk_ids=rejected_ids,
            rejection_reasons=reasons,
        )
