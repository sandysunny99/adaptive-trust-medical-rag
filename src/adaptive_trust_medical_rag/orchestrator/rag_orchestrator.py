class AdaptiveTrustRAGOrchestrator:
    """
    End-to-end Adaptive Trust-Aware Medical RAG Orchestrator.

    Wires together all 12 pipeline phases. All backends are injected
    via protocol interfaces for testability.

    Usage:
        orchestrator = AdaptiveTrustRAGOrchestrator(
            corpus=chunks,
            embedding_model=my_embedder,
            llm_backend=my_llm,
            drug_normalizer=my_normalizer,
        )
        response = orchestrator.query(RAGRequest(query="warfarin aspirin interaction"))
    """

    def __init__(
        self,
        corpus: list[Candidate],
        embedding_model: EmbeddingModel,
        llm_backend: LLMBackend,
        drug_normalizer: DrugNormalizerProtocol | None = None,
        drug_relationships: list[DrugRelationship] | None = None,
        grounding_validator = None,
        integrity_validator = None,
        retrieval_engine = None,
        **kwargs,
    ) -> None:
        self._trust_scorer = AdaptiveTrustScorer()
        self._prompt_detector = PromptInjectionDetector()
        self._poisoning_detector = RetrievalPoisoningDetector()
        self._auth_boundary = AuthorizationBoundary()
        self._tool_executor = ToolExecutor()
        self._eligibility_gate = EvidenceEligibilityGate()
        self._grounding_validator = grounding_validator
        self._integrity_validator = integrity_validator

        # Retrieval engine - pluggable or fallback
        if retrieval_engine is not None:
            self._retrieval = retrieval_engine
        else:
            self._retrieval = HybridRetrievalEngine(corpus, embedding_model)
            for rel in drug_relationships or []:
                self._retrieval.graph.add_relationship(rel)

        self._llm = llm_backend
        self._drug_normalizer = drug_normalizer

    # â”€â”€ Public API â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

    def query(self, request: RAGRequest) -> RAGResponse:
        """
        Execute the end-to-end Adaptive Trust-Aware RAG pipeline.
        """
        import uuid
        session_id = request.session_id or f"sess_{uuid.uuid4().hex[:8]}"
        request_id = f"req_{uuid.uuid4().hex[:8]}"
        
        security_context = SecurityContext(
            request_id=request_id,
            session_id=session_id,
            principal="USER"
        )
        
        audit: list[dict[str, Any]] = []

        def _log(step: str, detail: dict) -> None:
            audit.append({"step": step, "detail": detail})

        _log("session_start", {"session_id": session_id})

        # Phase 14: Step 1.5 - Prompt Injection Detection (BEFORE processing)
        # Using simple query, not yet sanitized, for injection detection
        injection_decision = self._prompt_detector.inspect(request.query, request_id)
        security_context.injection_status = injection_decision
        security_context.add_decision(injection_decision)
        _log("prompt_injection_detection", {"decision": injection_decision.decision.value, "reason": injection_decision.reason_code})
        
        if injection_decision.decision == SecurityState.BLOCK:
            return self._abstain(
                session_id=session_id,
                query_hash=hashlib.sha256(request.query.encode()).hexdigest(),
                risk_tier="R3",  # default high risk for malicious requests
                reason="Query blocked due to security policy (Prompt Injection).",
                audit=audit,
                security_context=security_context
            )

        # ðŸš€ Step 1: Input sanitization
        sanitization_result = sanitize_query(request.query)
        sanitized_query = sanitization_result.sanitized

        query_hash = hashlib.sha256(sanitized_query.encode()).hexdigest()
        _log("sanitization", {"query_hash": query_hash})

        if sanitization_result.rejected:
            # Re-evaluate with injection detector explicitly logging block
            return self._abstain(
                session_id=session_id,
                query_hash=query_hash,
                risk_tier="R0",
                reason="Query rejected by security sanitizer.",
                audit=audit,
                security_context=security_context
            )

        # ðŸš€ Step 2: Drug entity normalization
        if self._drug_normalizer:
            query_drugs = self._drug_normalizer.normalize(sanitized_query)
        else:
            query_drugs = self._extract_drugs_simple(sanitized_query)
        _log("entity_normalization", {"drugs": query_drugs})

        # Step 2.5: Build canonical drug RxCUI map
        drug_rxcui_map: dict[str, str] = {}
        if hasattr(self._drug_normalizer, '_cache'):
            cache = getattr(self._drug_normalizer, '_cache')
            for drug_name in query_drugs:
                cached = cache.lookup(drug_name)
                if cached and cached.get('rxcui'):
                    drug_rxcui_map[drug_name.lower()] = cached['rxcui']

        # ðŸš€ Step 3: Query risk classification
        if request.risk_tier_override:
            risk_tier = request.risk_tier_override
        else:
            risk_tier = classify_query_risk(sanitized_query)

        _log("risk_classification", {"risk_tier": risk_tier})

        # ðŸš€ Step 4: Hybrid retrieval
        candidates = self._retrieval.retrieve(
            query=sanitized_query,
            query_drugs=query_drugs,
            top_k=request.top_k,
        )

        _log(
            "retrieval",
            {
                "candidate_count": len(candidates),
                "chunk_ids": [sc.candidate.chunk_id for sc in candidates],
            },
        )
        
        # Phase 14: Step 4.5 - Retrieval Poisoning Detection
        retrieval_security_states = {}
        for sc in candidates:
            cand = sc.candidate
            poison_dec = self._poisoning_detector.inspect_provenance(cand.metadata.get("provenance", {}), cand.chunk_id, request_id)
            retrieval_security_states[cand.chunk_id] = poison_dec
            security_context.add_decision(poison_dec)
        security_context.retrieval_security_states = retrieval_security_states

        # ðŸš€ Step 5: Adaptive trust scoring
        trust_scores: dict[str, float] = {}
        missing_factors_dict: dict[str, list[str]] = {}
        for sc in candidates:
            cand = sc.candidate
            entity_match = 1.0 if any(d in cand.text.lower() for d in query_drugs) else 0.5
            factors = TrustFactorScores(
                source_authority=cand.source_authority,
                entity_match=entity_match,
                freshness=float(cand.metadata.get("freshness_score", 0.8)),
                consistency=1.0 - cand.poisoning_score,
                anti_poisoning=1.0 - cand.poisoning_score,
                anti_injection=1.0,  # FIXED: Default clean; injection is evaluated as a hard gate later
            )
            result = self._trust_scorer.score(
                chunk_id=cand.chunk_id,
                risk_class=risk_tier,
                factors=factors,
            )
            trust_scores[cand.chunk_id] = result.trust_score
            missing_factors_dict[cand.chunk_id] = result.missing_factors

        _log(
            "trust_scoring",
            {
                "scores": {cid: round(s, 4) for cid, s in trust_scores.items()},
            },
        )

        # Step 6: Evidence eligibility gate (pre-generation)
        grounding_states = {}
        integrity_states = {}
        candidate_injection_states = {}
        for sc in candidates:
            cand = sc.candidate
            if getattr(self, "_grounding_validator", None):
                # Backwards compatible: if validate accepts query, pass it
                import inspect
                sig = inspect.signature(self._grounding_validator.validate)
                if "query" in sig.parameters:
                    grounding_states[cand.chunk_id] = self._grounding_validator.validate(cand, query=request.query)
                else:
                    grounding_states[cand.chunk_id] = self._grounding_validator.validate(cand)
            if getattr(self, "_integrity_validator", None):
                integrity_states[cand.chunk_id] = self._integrity_validator.validate(cand)
            inj_dec = self._prompt_detector.inspect(cand.text, request_id)
            candidate_injection_states[cand.chunk_id] = inj_dec
            security_context.add_decision(inj_dec)

        eligibility = self._eligibility_gate.evaluate(candidates, risk_tier, trust_scores, retrieval_security_states, grounding_states, integrity_states, candidate_injection_states)

        _log(
            "evidence_eligibility_gate",
            {
                "passed": eligibility.passed,
                "eligible_count": len(eligibility.eligible_chunks),
                "rejected_ids": eligibility.rejected_chunk_ids,
                "reason": eligibility.reason,
                "rejection_reasons": eligibility.rejection_reasons,
            },
        )

        if not eligibility.passed:
            return self._abstain(
                session_id=session_id,
                query_hash=query_hash,
                risk_tier=risk_tier,
                reason=eligibility.reason or "Evidence eligibility gate failed.",
                audit=audit,
                security_context=security_context
            )

        eligible_candidates = eligibility.eligible_chunks



        # ðŸš€ Step 7: Grounded LLM generation
        prompt = build_grounded_prompt(sanitized_query, risk_tier, eligible_candidates)
        raw_answer = self._llm.generate(prompt)

        _log("llm_generation", {"prompt_length": len(prompt), "answer_length": len(raw_answer)})

        # ðŸš€ Step 7.5: Classify Output (Claim vs Action)
        # FAIL-CLOSED: malformed/unknown actions -> controlled abstention, never fallback
        try:
            action_request = parse_action_request(
                llm_output=raw_answer,
                principal=security_context.principal,
                request_id=request_id,
            )
        except ActionParseError as e:
            _log("action_parse_error", {"error": str(e)})
            return self._abstain(
                session_id=session_id,
                query_hash=query_hash,
                risk_tier=risk_tier,
                reason=f"Invalid action request in LLM output: {e}",
                audit=audit,
                security_context=security_context
            )
        
        if action_request is not None:
            _log("action_request_parsed", {
                "action_type": action_request.action_type.value,
                "domain": action_request.entity_domain.value,
                "principal": action_request.principal,
            })
            
            auth_decision = self._auth_boundary.authorize(
                domain=action_request.entity_domain,
                action=action_request.action_type,
                request_id=request_id,
                principal=action_request.principal
            )
            security_context.authorization_states.append(auth_decision)
            security_context.add_decision(auth_decision)
            _log("authorization_decision", {
                "decision": auth_decision.decision.value,
                "reason": auth_decision.reason_code,
            })
            
            if auth_decision.decision == SecurityState.UNAUTHORIZED_ACTION_REJECTED:
                return self._abstain(
                    session_id=session_id,
                    query_hash=query_hash,
                    risk_tier=risk_tier,
                    reason=f"Authorization Boundary Blocked Action: {action_request.action_type.value} on {action_request.entity_domain.value}.",
                    audit=audit,
                    security_context=security_context
                )
            
            # Authorized â€” execute via controlled executor
            exec_record = self._tool_executor.execute(action_request)
            _log("tool_execution", {
                "action_type": exec_record.action_type,
                "domain": exec_record.entity_domain,
                "success": exec_record.success,
            })
            return RAGResponse(
                session_id=session_id,
                query_hash=query_hash,
                risk_tier=risk_tier,
                status=PipelineStatus.released,
                answer=f"Tool {exec_record.action_type} executed on {exec_record.entity_domain}.",
                confidence=1.0,
                trust_scores=list(trust_scores.values()),
                retrieved_chunk_ids=[sc.candidate.chunk_id for sc in eligible_candidates],
                gate_decision="tool_executed",
                verification_report=None,
                audit_log=audit,
                security_events=security_context.cumulative_decisions
            )

        # ðŸš€ Step 8: Answer safety gate (post-generation)
        # Build source canonical identities
        source_identity = None
        if len(drug_rxcui_map) >= 2:
            rxcui_list = list(drug_rxcui_map.items())
            subject_name, subject_rxcui = rxcui_list[0]
            object_name, object_rxcui = rxcui_list[1]
            predicate = "INTERACTION"
            source_identity = CanonicalRelationshipIdentity(
                subject_rxcui=subject_rxcui,
                object_rxcui=object_rxcui,
                predicate=predicate,
                direction=CanonicalDirection.A_TO_B,
            )

        evidence_chunks = []
        for i, sc in enumerate(eligible_candidates, start=1):
            identity_copy = None
            if source_identity is not None:
                identity_copy = CanonicalRelationshipIdentity(
                    subject_rxcui=source_identity.subject_rxcui,
                    object_rxcui=source_identity.object_rxcui,
                    predicate=source_identity.predicate,
                    direction=source_identity.direction,
                    provenance_chunk_id=sc.candidate.chunk_id
                )
            evidence_chunks.append(
                EvidenceChunk(
                    chunk_id=sc.candidate.chunk_id,
                    text=sc.candidate.text,
                    source_authority=sc.candidate.source_authority,
                    citation_index=i,
                    trust_score=trust_scores.get(sc.candidate.chunk_id, 0.0),
                    missing_factors=missing_factors_dict.get(sc.candidate.chunk_id, []),
                    relationship_scope=grounding_states[sc.candidate.chunk_id].status.name if (grounding_states and sc.candidate.chunk_id in grounding_states) else None,
                    relationship_identity=identity_copy
                )
            )

        safety_gate = AnswerSafetyGate(risk_tier=risk_tier)
        verification = safety_gate.verify(raw_answer, evidence_chunks)

        _log(
            "answer_safety_gate",
            {
                "decision": verification.decision.value,
                "confidence": verification.confidence,
                "grounding_ratio": verification.grounding_ratio,
                "contradiction_score": verification.contradiction_score,
                "explanation": verification.explanation,
            },
        )

        # ðŸš€ Step 9: Final answer formatting

        if verification.decision == GateDecision.abstain:
            return self._abstain(
                session_id=session_id,
                query_hash=query_hash,
                risk_tier=risk_tier,
                reason=verification.explanation,
                audit=audit,
                verification=verification,
                trust_scores=list(trust_scores.values()),
                chunk_ids=[sc.candidate.chunk_id for sc in eligible_candidates],
                security_context=security_context
            )

        final_answer = (
            verification.qualified_answer
            if verification.decision == GateDecision.qualify and verification.qualified_answer
            else raw_answer
        ) + RESEARCH_DISCLAIMER

        status = (
            PipelineStatus.qualified
            if verification.decision == GateDecision.qualify
            else PipelineStatus.released
        )

        return RAGResponse(
            session_id=session_id,
            query_hash=query_hash,
            risk_tier=risk_tier,
            status=status,
            answer=final_answer,
            confidence=verification.confidence,
            trust_scores=list(trust_scores.values()),
            retrieved_chunk_ids=[sc.candidate.chunk_id for sc in eligible_candidates],
            gate_decision=verification.decision.value,
            verification_report=verification,
            audit_log=audit,
            security_events=security_context.cumulative_decisions
        )



