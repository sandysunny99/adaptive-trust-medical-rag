"""
Phase 17 - End-to-End Evaluation Pipeline.

Orchestrates the complete ablation study evaluation:
  1. Load benchmark dataset (smoke / dev / val)
  2. Instantiate all 6 pipeline variant callables (A-F)
  3. Run AblationRunner against the dataset
  4. Log every run to ExperimentTracker (MLflow or JSONL)
  5. Generate Markdown results report + save to experiments/reports/
  6. Return structured EvalPipelineResult

Usage (library):
    result = run_evaluation(split=DatasetSplit.dev)
    print(result.report.summary_table())
    print(result.markdown_report)

Usage (CLI):
    python -m adaptive_trust_medical_rag.evaluation.eval_pipeline --split dev

Privacy: No raw queries or PHI are logged. Only metrics + config hashes.
Research integrity: Test set guarded. Fixtures never used for tuning.
"""

