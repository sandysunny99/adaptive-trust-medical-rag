"""Unit and integration tests for user-selectable LLM answer generation.

Verifies:
1. GET /api/v1/llm/models catalog endpoint returns supported models and status.
2. Server-side validation strictly enforces model IDs and provider pairing.
3. Prescription upload endpoint rejects invalid llm_selection without silent fallback.
4. LiveProviderRouter supports explicit provider routing without silent failover.
5. Behavioral four-way component isolation:
   - User LLM: Final analysis generation ONLY.
   - PubMedBERT-MNLI-MedNLI: Claim verification ONLY.
   - all-MiniLM-L6-v2 (384-d): Dense retrieval embeddings ONLY.
   - Vision model: Prescription OCR extraction ONLY.
"""

