"""Unit and integration tests for user-selectable LLM answer generation.

Verifies:
1. GET /api/v1/llm/models catalog endpoint returns supported models and status.
2. LiveProviderRouter supports explicit provider routing without silent failover.
3. Analysis API accepts llm_selection (auto and manual modes).
4. Component separation invariant: LLM selection does NOT alter ClaimVerifier,
   embedding space, or vision models.
"""

import json
import pytest
from fastapi.testclient import TestClient

from adaptive_trust_medical_rag.api.app import app
from adaptive_trust_medical_rag.common.model_result import ModelExecutionError
from adaptive_trust_medical_rag.llm_backend.interfaces import ProviderAdapter, ProviderResponse
from adaptive_trust_medical_rag.llm_backend.live_provider_router import LiveProviderRouter
from adaptive_trust_medical_rag.llm_backend.model_registry import (
    SUPPORTED_LLM_MODELS,
    get_available_models,
)

client = TestClient(app)


class MockTestProvider(ProviderAdapter):
    def __init__(self, name: str, model: str):
        self.provider_name = name
        self.model_name = model
        self.call_count = 0

    def initialize(self): pass
    async def health_check(self): return True
    async def generate(self, prompt: str): return None
    async def stream(self, prompt: str): return None
    def normalize_error(self, e): return None
    def get_model_metadata(self): return {}

    async def generate_structured(self, prompt: str, response_format: dict | None = None) -> ProviderResponse:
        self.call_count += 1
        payload = {
            "conclusion": f"Generated by {self.provider_name}:{self.model_name}",
            "interactions": [],
            "adverse_reactions": [],
            "warnings": [],
            "food_guidance": [],
            "patient_considerations": [],
            "claims_for_verification": [],
        }
        return ProviderResponse(
            provider=self.provider_name,
            model=self.model_name,
            request_id="test-req",
            content=json.dumps(payload),
            structured_output=payload,
            usage={},
            latency_ms=10.0,
            finish_reason="stop",
            transport_status=200,
            raw_metadata={},
        )


def test_model_catalog_endpoint():
    """Verify GET /api/v1/llm/models returns valid schema and model list."""
    res = client.get("/api/v1/llm/models")
    assert res.status_code == 200
    data = res.json()

    assert "models" in data
    assert "default_mode" in data
    assert data["default_mode"] == "auto"

    models = data["models"]
    assert len(models) >= len(SUPPORTED_LLM_MODELS)

    model_ids = [m["id"] for m in models]
    assert "nvidia/nemotron-3-super-120b-a12b" in model_ids
    assert "openai/gpt-oss-120b" in model_ids
    assert "mock-llm" in model_ids

    for m in models:
        assert "id" in m
        assert "provider" in m
        assert "name" in m
        assert "description" in m
        assert "is_available" in m
        assert isinstance(m["is_available"], bool)


def test_model_registry_availability():
    """Verify availability helper correctly identifies models."""
    models = get_available_models(app.state)
    assert len(models) > 0
    # In testing mode (TESTING=1), models should be marked available
    for m in models:
        assert m["is_available"] is True


@pytest.mark.asyncio
async def test_live_provider_router_direct_routing():
    """Verify manual provider selection routes directly without failover."""
    p_primary = MockTestProvider("provider_a", "model_a")
    p_secondary = MockTestProvider("provider_b", "model_b")

    router = LiveProviderRouter(provider_priority=["provider_a", "provider_b"])
    router.register_provider("provider_a", p_primary)
    router.register_provider("provider_b", p_secondary)

    # 1. Automatic mode -> should use first priority (provider_a)
    res_auto = await router.generate_structured("prompt", {})
    assert res_auto.provider == "provider_a"
    assert p_primary.call_count == 1
    assert p_secondary.call_count == 0

    # 2. Explicit direct routing to provider_b
    res_manual = await router.generate_structured("prompt", {}, provider_name="provider_b")
    assert res_manual.provider == "provider_b"
    assert p_secondary.call_count == 1

    # 3. Direct routing to non-existent provider must raise error without silent failover
    with pytest.raises(ModelExecutionError) as exc_info:
        await router.generate_structured("prompt", {}, provider_name="non_existent")
    assert "not registered" in str(exc_info.value) or "PROVIDER_NOT_FOUND" in str(exc_info.value)


def test_analyze_request_with_model_selection():
    """Verify POST /api/v1/analyze accepts llm_selection payload."""
    payload_auto = {
        "drug_names": ["Warfarin"],
        "input_mode": "direct_drugs",
        "llm_selection": {
            "mode": "auto",
        },
    }
    res_auto = client.post("/api/v1/analyze", json=payload_auto)
    assert res_auto.status_code == 200
    assert "request_id" in res_auto.json()

    payload_manual = {
        "drug_names": ["Warfarin"],
        "input_mode": "direct_drugs",
        "llm_selection": {
            "mode": "manual",
            "model_id": "nvidia/nemotron-3-super-120b-a12b",
            "provider": "nvidia",
        },
    }
    res_manual = client.post("/api/v1/analyze", json=payload_manual)
    assert res_manual.status_code == 200
    assert "request_id" in res_manual.json()


