class MockTestProvider(ProviderAdapter):
    def __init__(self, name: str, model: str, should_fail: bool = False, failure_class: FailureClass = FailureClass.UNKNOWN):
        self.provider_name = name
        self.model_name = model
        self.should_fail = should_fail
        self.failure_class = failure_class
        self.call_count = 0

    def initialize(self): pass
    async def health_check(self): return True
    async def generate(self, prompt: str): return None
    async def stream(self, prompt: str): return None
    def normalize_error(self, e): return None
    def get_model_metadata(self): return {"provider": self.provider_name, "model": self.model_name}

    async def generate_structured(self, prompt: str, response_format: dict | None = None) -> ProviderResponse:
        self.call_count += 1
        if self.should_fail:
            err = ModelExecutionError(f"Simulated failure on {self.provider_name}", status_code="TEST_FAIL")
            err.failure_class = self.failure_class
            raise err

        payload = {
            "conclusion": f"Generated by {self.provider_name}:{self.model_name}",
            "interactions": [],
            "adverse_reactions": [],
            "warnings": [],
            "food_guidance": [],
            "patient_considerations": [],
            "claims_for_verification": [],
        }
        return ProviderResponse(
            provider=self.provider_name,
            model=self.model_name,
            request_id="test-req",
            content=json.dumps(payload),
            structured_output=payload,
            usage={},
            latency_ms=10.0,
            finish_reason="stop",
            transport_status=200,
            raw_metadata={},
        )


def _create_test_image_bytes() -> bytes:
    """Generate a minimal valid PNG image for upload testing."""
    img = Image.new("RGB", (100, 100), color=(255, 255, 255))
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


def test_model_catalog_endpoint():
    """Verify GET /api/v1/llm/models returns valid schema, correct model names, and default mode."""
    res = client.get("/api/v1/llm/models")
    assert res.status_code == 200
    data = res.json()

    assert "models" in data
    assert "default_mode" in data
    assert data["default_mode"] == "auto"

    models = data["models"]
    assert len(models) >= len(SUPPORTED_LLM_MODELS)

    model_map = {m["id"]: m for m in models}
    assert "nvidia/nemotron-3-super-120b-a12b" in model_map
    assert "openai/gpt-oss-120b" in model_map
    assert "@cf/meta/llama-3.3-70b-instruct-fp8-fast" in model_map
    assert "mock-llm" in model_map

    # Ensure Groq model name is consistently aligned to GPT-OSS 120B (not Llama-3.3)
    groq_model = model_map["openai/gpt-oss-120b"]
    assert groq_model["name"] == "Groq GPT-OSS 120B"
    assert groq_model["provider"] == "groq"

    for m in models:
        assert "id" in m
        assert "provider" in m
        assert "name" in m
        assert "description" in m
        assert "is_available" in m
        assert isinstance(m["is_available"], bool)


