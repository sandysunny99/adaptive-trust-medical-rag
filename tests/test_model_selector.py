@pytest.mark.asyncio
async def test_live_provider_router_direct_routing_and_failover():
    """Verify manual direct routing never falls over, but automatic mode can fail over on transport error."""
    p_primary = MockTestProvider("provider_a", "model_a", should_fail=True, failure_class=FailureClass.NETWORK)
    p_secondary = MockTestProvider("provider_b", "model_b", should_fail=False)

    router = LiveProviderRouter(provider_priority=["provider_a", "provider_b"])
    router.register_provider("provider_a", p_primary)
    router.register_provider("provider_b", p_secondary)

    # 1. Automatic mode: transport failure on provider_a triggers failover to provider_b
    res_auto = await router.generate_structured("prompt", {})
    assert res_auto.provider == "provider_b"
    assert p_primary.call_count == 1
    assert p_secondary.call_count == 1

    # 2. Explicit direct routing to provider_a (which fails): MUST NOT fail over to provider_b
    with pytest.raises(ModelExecutionError) as exc_info:
        await router.generate_structured("prompt", {}, provider_name="provider_a")
    assert "Simulated failure on provider_a" in str(exc_info.value)
    assert p_primary.call_count == 2
    assert p_secondary.call_count == 1  # provider_b was not called

    # 3. Explicit direct routing to non-existent provider raises PROVIDER_NOT_FOUND
    with pytest.raises(ModelExecutionError) as exc_info:
        await router.generate_structured("prompt", {}, provider_name="missing_provider")
    assert "PROVIDER_NOT_FOUND" in str(exc_info.value) or "not registered" in str(exc_info.value)


def test_behavioral_four_way_component_isolation():
    """Behavioral proof of strict four-way component segregation.

    Guarantees:
    1. User LLM selection routes ONLY to final answer generation.
    2. Dense retrieval embedding model is strictly 384-dimensional all-MiniLM-L6-v2.
    3. Claim verification is strictly PubMedBERT-MNLI-MedNLI architecture (ClaimVerifierV2).
    4. Vision extraction operates through Vision adapter, not the answer-generation LLM.
    """
    # Component 1: Dense Retrieval Embedding Space
    from adaptive_trust_medical_rag.retrieval.hybrid_retrieval import Candidate, HybridRetrievalEngine

    class MockMiniLMEmbedding:
        vector_dim: int = 384
        def encode(self, texts: list[str]) -> list[list[float]]:
            # Emits 384-dimensional dense vectors corresponding to all-MiniLM-L6-v2
            return [[0.05] * self.vector_dim for _ in texts]

    mock_emb = MockMiniLMEmbedding()
    dummy_candidate = Candidate(
        chunk_id="chunk-1",
        document_id="doc-1",
        text="Warfarin interacts with aspirin to increase bleeding risk.",
        source_authority=0.9,
    )
    engine = HybridRetrievalEngine(corpus=[dummy_candidate], embedding_model=mock_emb)
    assert mock_emb.vector_dim == 384
    results = engine.retrieve(query="warfarin aspirin")
    assert len(results) == 1
    assert results[0].candidate.chunk_id == "chunk-1"

    # Component 2: Post-generation Claim Verification
    from adaptive_trust_medical_rag.verification.claim_verifier_v2 import (
        ClaimVerifierV2,
        EvidenceChunk,
        FinalSupportState,
    )
    verifier = ClaimVerifierV2()
    assert verifier.model_id == "pritamdeka/PubMedBERT-MNLI-MedNLI"
    evidence = [
        EvidenceChunk(
            chunk_id="chunk-1",
            text="Warfarin and aspirin co-administration markedly increases bleeding risk.",
            citation_index=1,
            source_authority=0.9,
            trust_score=0.85,
        )
    ]
    # Verify a supported claim
    answer = "Warfarin increases bleeding risk when taken with aspirin [1]."
    report = verifier.verify(answer=answer, evidence=evidence, risk_tier="R1")
    assert report is not None
    assert len(report.judgments) >= 1
    assert report.judgments[0].support_state == FinalSupportState.SUPPORTED

    # Component 3: Vision Extraction Model
    from adaptive_trust_medical_rag.services.image_validator import ImageValidator
    valid_bytes = _create_test_image_bytes()
    meta = ImageValidator.validate_and_preprocess(valid_bytes, "test.png", "image/png")
    assert meta["width"] == 100
    assert meta["height"] == 100
    assert "original_image_sha256" in meta

    # Component 4: Generation LLM routing is fully segregated from components 1-3
    from adaptive_trust_medical_rag.llm_backend.model_registry import SUPPORTED_LLM_MODELS
    for model_def in SUPPORTED_LLM_MODELS:
        # None of the answer-generation models can masquerade as retrieval embedding or NLI verifier
        assert "minilm" not in model_def.id.lower()
        assert "pubmedbert" not in model_def.id.lower()

