def test_server_side_validation_matrix():
    """Verify validate_llm_selection helper enforces strict server-side rules."""
    # 1. Auto mode is always valid
    ok, err, m_def = validate_llm_selection(None, app.state)
    assert ok is True and err is None and m_def is None

    ok, err, m_def = validate_llm_selection({"mode": "auto"}, app.state)
    assert ok is True and err is None and m_def is None

    # 2. Manual mode with valid model ID and correct provider
    ok, err, m_def = validate_llm_selection({
        "mode": "manual",
        "model_id": "nvidia/nemotron-3-super-120b-a12b",
        "provider": "nvidia",
    }, app.state)
    assert ok is True and err is None
    assert m_def is not None and m_def.id == "nvidia/nemotron-3-super-120b-a12b"

    # 3. Manual mode with omitted provider correctly resolves from registry
    ok, err, m_def = validate_llm_selection({
        "mode": "manual",
        "model_id": "openai/gpt-oss-120b",
    }, app.state)
    assert ok is True and err is None
    assert m_def is not None and m_def.provider == "groq"

    # 4. Manual mode with unknown model ID is rejected
    ok, err, m_def = validate_llm_selection({
        "mode": "manual",
        "model_id": "unsupported-llm-999",
    }, app.state)
    assert ok is False
    assert "Unsupported or unknown model ID" in err

    # 5. Manual mode with provider mismatch is rejected
    ok, err, m_def = validate_llm_selection({
        "mode": "manual",
        "model_id": "openai/gpt-oss-120b",
        "provider": "nvidia",  # Mismatch: openai/gpt-oss-120b belongs to groq
    }, app.state)
    assert ok is False
    assert "Provider mismatch" in err

    # 6. Manual mode without model_id is rejected
    ok, err, m_def = validate_llm_selection({
        "mode": "manual",
    }, app.state)
    assert ok is False
    assert "requires a valid 'model_id'" in err


